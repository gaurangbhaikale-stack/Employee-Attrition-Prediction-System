# --------------------------------------------------------------------------
# Load model, encoder, scaler (exact objects saved by the notebook)
# --------------------------------------------------------------------------
@st.cache_resource
def load_artifacts():
    with open("model.pkl", "rb") as file:
        model = pickle.load(file)
    with open("encoder.pkl", "rb") as file:
        he = pickle.load(file)
    with open("sk.pkl", "rb") as file:
        sk = pickle.load(file)
    return model, he, sk


try:
    model, he, sk = load_artifacts()
    artifacts_loaded = True
except FileNotFoundError as e:
    artifacts_loaded = False
    missing_file = str(e)

if not artifacts_loaded:
    st.error(
        "Could not find one or more required files (model.pkl, encoder.pkl, sk.pkl) "
        "in the app's working directory.\n\n"
        f"Details: {missing_file}\n\n"
        "Run the notebook's save cells (42, 43, 46) first and place the "
        "resulting .pkl files next to app.py."
    )
    st.stop()

# JobRole categories exactly as seen in the notebook (Cell 11 output)
JOB_ROLES = [
    "Laboratory Technician",
    "Sales Representative",
    "Research Scientist",
    "Human Resources",
    "Manufacturing Director",
    "Sales Executive",
    "Healthcare Representative",
    "Research Director",
    "Manager",
]

# Verified target mapping (see module docstring): No -> 0, Yes -> 1
LABEL_MAP = {0: "No", 1: "Yes"}

# Exact training feature order (Cell 44 output / columns.txt)
TRAINING_COLUMNS = [
    "Age",
    "YearsAtCompany",
    "MonthlyIncome",
    "PerformanceRating",
    "JobSatisfaction",
    "WorkLifeBalance",
    "JobRole_Healthcare Representative",
    "JobRole_Human Resources",
    "JobRole_Laboratory Technician",
    "JobRole_Manager",
    "JobRole_Manufacturing Director",
    "JobRole_Research Director",
    "JobRole_Research Scientist",
    "JobRole_Sales Executive",
    "JobRole_Sales Representative",
]

# --------------------------------------------------------------------------
# Input form
# --------------------------------------------------------------------------
with st.form("prediction_form"):
    st.subheader("Employee Details")

    col1, col2 = st.columns(2)

    with col1:
        Age = st.number_input("Age", min_value=18, max_value=60, value=30, step=1)
        JobRole = st.selectbox("Job Role", JOB_ROLES)
        YearsAtCompany = st.number_input("Years At Company", min_value=0, max_value=40, value=5, step=1)
        MonthlyIncome = st.number_input("Monthly Income", min_value=0, value=5000, step=100)

    with col2:
        PerformanceRating = st.selectbox("Performance Rating", [1, 2, 3, 4])
        JobSatisfaction = st.selectbox("Job Satisfaction", [1, 2, 3, 4])
        WorkLifeBalance = st.selectbox("Work Life Balance", [1, 2, 3, 4])

    submitted = st.form_submit_button("Predict")

# --------------------------------------------------------------------------
# Prediction pipeline — mirrors the notebook exactly
# --------------------------------------------------------------------------
if submitted:
    # Step 1: build x with the same raw columns/order as Cell 6
    x = pd.DataFrame()
    x['Age'] = [Age]
    x['JobRole'] = [JobRole]
    x['YearsAtCompany'] = [YearsAtCompany]
    x['MonthlyIncome'] = [MonthlyIncome]
    x['PerformanceRating'] = [PerformanceRating]
    x['JobSatisfaction'] = [JobSatisfaction]
    x['WorkLifeBalance'] = [WorkLifeBalance]

    # Step 2: OneHotEncode JobRole with the SAVED encoder (Cells 18-21)
    encoded = he.transform(x[['JobRole']])
    encoded = encoded.toarray()
    encoded_d = pd.DataFrame(encoded, columns=he.get_feature_names_out(['JobRole']))

    # Step 3: drop JobRole, concat one-hot columns (Cells 22-23)
    x = x.drop('JobRole', axis=1)
    x = pd.concat([x, encoded_d], axis=1)

    # Ensure column order exactly matches training order (columns.txt)
    x = x[TRAINING_COLUMNS]

    # Step 4: scale with the SAVED StandardScaler (Cell 29)
    x_scaled = sk.transform(x)

    # Step 5: predict with the SAVED LogisticRegression model (Cell 32)
    y_pred = model.predict(x_scaled)
    prediction = int(y_pred[0])
    label = LABEL_MAP[prediction]

    if label == "No":
        st.markdown(
            '<div class="result-box stay">✅ Employee is likely to STAY</div>',
            unsafe_allow_html=True,
        )
    else:
        st.markdown(
            '<div class="result-box leave">⚠️ Employee is likely to LEAVE</div>',
            unsafe_allow_html=True,
        )

    with st.expander("View processed feature vector"):
        st.dataframe(x)
