"""
Employee Attrition Prediction System
-------------------------------------
This app reproduces, EXACTLY, the preprocessing + inference pipeline built in
Attrition_Prediction.ipynb:

    1. Raw features assembled in this order (Cell 6):
       Age, JobRole, YearsAtCompany, MonthlyIncome, PerformanceRating,
       JobSatisfaction, WorkLifeBalance

    2. OneHotEncoder `he` (Cell 17) fit_transform on x[['JobRole']] (Cell 18)
       -> encoded.toarray() (Cell 20)
       -> encoded_d = pd.DataFrame(encoded, columns=he.get_feature_names_out(['JobRole'])) (Cell 21)

    3. x = x.drop('JobRole', axis=1) (Cell 22)
       x = pd.concat([x, encoded_d], axis=1) (Cell 23)

    4. StandardScaler `sk` (Cell 28) fit_transform on x_train, which is the
       FULL 15-column post-encoding frame (Cell 29). At inference time we
       therefore call sk.transform() on the full 15-column frame too.

    5. LogisticRegression `model` (Cell 31) predicts on the scaled array.

    6. Target mapping: the notebook's LabelEncoder `le` was fit on
       'Attrition' (Cell 13-14) but NEVER pickled (no save cell exists).
       Cross-checking Cell 10 (raw values) against Cell 15 (encoded values)
       confirms sklearn's default alphabetical mapping was produced:
           No  -> 0
           Yes -> 1
       This mapping is hardcoded below since it was verified from the
       notebook's own outputs, not assumed.

Required files (place alongside this app.py — generated by running the
notebook's save cells 42, 43, 46):
    - model.pkl    (LogisticRegression)
    - encoder.pkl  (OneHotEncoder `he`)
    - sk.pkl       (StandardScaler `sk`)
"""

